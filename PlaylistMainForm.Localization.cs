    private readonly ToolTip localizedToolTip = new();
    private readonly Dictionary<Control, string> localizedHints = [];
    private string statusKey = "ready";
    private object?[] statusArguments = [];

    private static string TextForLanguage(string language, string key) =>
        (Translations.TryGetValue(language, out var texts) ? texts : Translations["en"])[key];

    // ExecutionContext carries the selected UI culture into static async helpers.
    private static string S(string key, params object?[] args) => string.Format(
        CultureInfo.CurrentCulture, TextForLanguage(CultureInfo.CurrentUICulture.TwoLetterISOLanguageName, key), args);

    private void ApplyLanguage() => CultureInfo.CurrentUICulture = CultureInfo.GetCultureInfo(
        Translations.ContainsKey(CurrentLanguage()) ? CurrentLanguage() : "en");

    private void SetStatus(string key, params object?[] args)
    {
        statusKey = key;
        statusArguments = args;
        status.Text = string.Format(CultureInfo.CurrentCulture, T(key), args);
    }

    private void RefreshStatus()
    {
        if (paused) SetStatus("paused");
        else if (player.IsPlaying) SetStatus("playingTrack", currentTrack?.Name, PlaybackSource());
        else SetStatus(statusKey, statusArguments);
    }

    private void RegisterLocalizedHint(Control control, string key)
    {
        localizedHints[control] = key;
        control.AccessibleName = T(key);
        localizedToolTip.SetToolTip(control, T(key));
    }

    private void RefreshLocalizedHints()
    {
        foreach (var (control, key) in localizedHints.ToArray())
        {
            if (control.IsDisposed) { localizedHints.Remove(control); continue; }
            control.AccessibleName = T(key);
            localizedToolTip.SetToolTip(control, T(key));
        }
    }

    private static Form LocalizeDialog(Form dialog)
    {
        dialog.RightToLeft = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName == "he" ? RightToLeft.Yes : RightToLeft.No;
        return dialog;
    }

